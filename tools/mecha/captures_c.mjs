// Gameplay captures of the mission from the RTS camera (window captures; crop them to the printed viewport).
import { wzx } from './wzx.mjs';
const sleep = (s) => new Promise((r) => setTimeout(r, s * 1000));
const shot = async (label) => { const r = await wzx('screenshot', { window: true }); console.log(`SHOT ${label} ${r.path}`); };
console.log('VIEWPORT', JSON.stringify((await wzx('state')).viewport));
await wzx('play');
await sleep(2);
await shot('intro');
await wzx('input.ok');
const st = await wzx('rts.state');
const workers = st.units.filter((u) => u.prefab === 'MechaWorker').map((u) => u.index);
const tanks = st.units.filter((u) => u.prefab === 'VitaeTanks').sort((a, b) => Math.hypot(...a.pos) - Math.hypot(...b.pos));
await wzx('input.select', { targets: workers });
await sleep(0.5);
await shot('default_zoom');
await wzx('rts.camera', { distance: 55 });
await sleep(0.6);
await shot('max_zoom_out');
await wzx('rts.camera', { target: [2, 0, 2], distance: 36 });
await wzx('input.rightclick', { target: tanks[0].index });
await sleep(4.5);
await wzx('rts.camera', { target: [tanks[0].pos[0] - 2, 0, tanks[0].pos[1]], distance: 20 });
await sleep(0.5);
await shot('harvest_close');
await sleep(2.5);
await wzx('rts.camera', { target: [3, 0, 1.5], distance: 30 });
await sleep(0.4);
await shot('carrying');
await wzx('stop');
